import type { LessonSummary, Phase } from '@/types/content';

function toSlug(text: string): string {
  return text
    .toLowerCase()
    .replace(/&/g, 'dan')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function createLessons(phaseId: string, titles: string[]): LessonSummary[] {
  return titles.map((title) => ({ id: `${phaseId}-${toSlug(title)}`, title }));
}

